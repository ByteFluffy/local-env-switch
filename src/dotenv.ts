import { parseEnv } from 'node:util';

export function assertString(value: unknown, label: string): asserts value is string {
  if (typeof value !== 'string') throw new Error(`${label} must be a string`);
}

export function assertBoolean(value: unknown, label: string): asserts value is boolean {
  if (typeof value !== 'boolean') throw new Error(`${label} must be a boolean`);
}

export function normalizeStringRecord(
  value: unknown,
  label: string,
): Record<string, string> {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${label} must be an object with string values`);
  }
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) {
    throw new Error(`${label} must be a plain object with string values`);
  }
  const entries = Object.entries(value);
  for (const [key, item] of entries) {
    if (typeof item !== 'string') {
      throw new Error(`${label} value for ${key} must be a string`);
    }
  }
  return Object.fromEntries(entries);
}

export function isPortableEnvironmentKey(key: string): boolean {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && key !== '__proto__';
}

export function parseDotEnv(source: string): Record<string, string> {
  if (/^\s*(?:export\s+)?__proto__\s*=/m.test(source)) {
    throw new Error('Unsupported environment key: __proto__');
  }
  try {
    const parsed = parseEnv(source);
    const entries: Array<[string, string]> = [];
    for (const [key, value] of Object.entries(parsed)) {
      if (!isPortableEnvironmentKey(key)) throw new Error('invalid environment key');
      if (value === undefined) throw new Error('undefined dotenv value');
      entries.push([key, value]);
    }
    return Object.fromEntries(entries);
  } catch {
    throw new Error('Invalid dotenv content');
  }
}

export function encodeDotEnvValue(key: string, value: string): string {
  if (value.includes('\0') || value.includes('\r') || value.includes('$')) {
    throw new Error(`Environment key ${key} cannot be represented portably in dotenv`);
  }
  if (value === '') return "''";
  if (/^[^\s#'"]+$/.test(value)) return value;
  if (!value.includes("'") && !value.endsWith('\\')) return `'${value}'`;
  if (!value.includes('"') && !value.endsWith('\\') && !/\\[nr]/.test(value)) return `"${value}"`;
  throw new Error(`Environment key ${key} cannot be represented portably in dotenv`);
}

export function serializeGeneratedEnv(input: {
  toolName: string;
  environment: string;
  localRedis: boolean;
  values: Record<string, string>;
}): string {
  assertString(input.toolName, 'toolName');
  assertString(input.environment, 'environment');
  assertBoolean(input.localRedis, 'localRedis');
  const values = normalizeStringRecord(input.values, 'values');
  if (/[\r\n]/.test(input.toolName)) {
    throw new Error('toolName must not contain line breaks');
  }
  if (/[\r\n]/.test(input.environment)) {
    throw new Error('environment must not contain line breaks');
  }

  const lines = [
    `# GENERATED by ${input.toolName} — do not edit by hand`,
    `# CURRENT_ENV=${input.environment} LOCAL_REDIS=${input.localRedis ? '1' : '0'}`,
  ];
  for (const key of Object.keys(values).sort()) {
    if (!isPortableEnvironmentKey(key)) {
      throw new Error(`Invalid environment key: ${key}`);
    }
    lines.push(`${key}=${encodeDotEnvValue(key, values[key])}`);
  }
  return `${lines.join('\n')}\n`;
}

export function parseGeneratedHeader(
  source: string,
  toolName: string,
  environments: readonly string[],
): { environment: string; localRedis: boolean } {
  const escapedTool = toolName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const envAlt = environments.map((e) => e.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
  const match = source.match(
    new RegExp(
      `^# GENERATED by ${escapedTool} — do not edit by hand\\r?\\n# CURRENT_ENV=(${envAlt}) LOCAL_REDIS=([01])(?:\\r?\\n|$)`,
    ),
  );
  if (!match?.[1] || !environments.includes(match[1])) {
    throw new Error(`Root .env was not generated by ${toolName}`);
  }
  return {
    environment: match[1],
    localRedis: match[2] === '1',
  };
}
